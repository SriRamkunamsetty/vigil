"""Writes docs/EVALUATION.md from artifacts/eval/results.json so the numbers can never drift."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
r = json.loads((ROOT / "artifacts/eval/results.json").read_text(encoding="utf-8"))
c, ex, net = r["conversations"], r["exchange"], r["network"]


def pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f}%"


def rng(ci: list[float]) -> str:
    return f"{pct(ci[0])}–{pct(ci[1])}"


rows = "\n".join(
    f"| {s['system']} | {pct(s['friction']['recall'])} ({rng(s['friction']['recall_ci'])}) | "
    f"{pct(s['friction']['fpr'], 2)} ({rng(s['friction']['fpr_ci'])}) | {pct(s['friction']['precision'])} | "
    f"{pct(s['nudge_or_higher']['recall'])} / {pct(s['nudge_or_higher']['fpr'])} | {s['pr_auc']:.3f} |"
    for s in c["systems"]
)
lang = "\n".join(
    f"| {k} | {v['n']} | {pct(v['recall'])} |" for k, v in c["fused_recall_by_language"].items()
)
kind = "\n".join(
    f"| {k.replace('_', ' ')} | {v['n']} | {pct(v['recall'])} |"
    for k, v in sorted(c["fused_recall_by_scam_type"].items(), key=lambda kv: kv[1]["recall"])
)
fam = c["fused_recall_by_wording_family"]
tr = c["fused_recall_by_transcript_available"]
benign = "\n".join(
    f"| {k.replace('_', ' ')} | {v['n']} | {pct(v['nudge_rate'])} | {pct(v['friction_or_hold_rate'])} |"
    for k, v in sorted(
        c["benign_friction_by_kind"].items(), key=lambda kv: -kv[1]["friction_or_hold_rate"]
    )
)
nrules = "\n".join(
    f"| {k} | {v['flagged']} | {pct(v['precision'])} | {pct(v['recall'])} | {v['hard_negatives_flagged']} |"
    for k, v in net["rules"].items()
)
t = c["time_to_intervene"]

doc = f"""# Evaluation

> Generated by `scripts/gen_eval_doc.py` from `artifacts/eval/results.json` (`{r["model_version"]}`).
> Reproduce with `make eval`. Do not edit by hand.

**Read this first.** {r["disclaimer"]} The data was written by the same people who wrote the detector. These
numbers show how approaches compare with each other on identical inputs. They do **not** estimate how Vigil
would perform on real fraud, and no figure here should be quoted as real-world accuracy.

## What was tested

| Part | Data | Size |
| --- | --- | --- |
| Conversation + payment fusion | Synthetic scam and genuine scenarios in English, Hindi, Hinglish and Telugu | {c["n"]:,} cases, {pct(c["scam_share"])} scams, seed {c["seed"]} |
| Cross-bank signal sharing | Synthetic payment-only scams where scammers reuse payees | {ex["n"]:,} cases |
| Mule-account detection | Synthetic transfer graph with injected rings and look-alike honest accounts | {net["accounts"]:,} accounts, {net["transfers"]:,} transfers |

Design choices that keep the test from being trivially easy:

* **Two wording families.** Each scam type has *seen* phrasings (the ones the lexicon was written from) and
  *unseen* paraphrases. We report both, because a rule system always looks good on its own wording.
* **Hard negatives.** Ten kinds of honest situations that resemble scams: genuine bank advisories that mention
  OTPs, real police verification, a real family emergency, paying a new landlord, buying a used car, and so on.
* **Held-out split.** Weights were set by hand and tuned on a development set generated with different seeds.
  The numbers below use a separate test seed that was not used for tuning.
* **Transcript missing.** 15% of cases have no transcript, as when a call is not monitored.

## 1. Scams caught versus honest customers bothered

“Friction level” means Vigil asked the customer to slow down or held the payment. Ranges are 95% Wilson intervals.

| Approach | Scams caught | False alarms | Precision | Caught / false alarms at heads-up level | PR-AUC |
| --- | --- | --- | --- | --- | --- |
{rows}

Fusing the conversation with the payment catches more scams than either signal alone at a low false-alarm rate.
Precision here depends on the {pct(c["scam_share"], 0)} scam share of the test set. At a realistic 1% prevalence
the fused system's precision is about {pct(next(s for s in c["systems"] if s["system"] == "Vigil fused")["precision_at_1pct"])}
(`precision_at_1pct`), so a deployment would need review capacity for many false alarms.

## 2. Where it is weak

**Wording.** Recall at friction level for familiar wording is {pct(fam["seen"]["recall"])} and for paraphrased
wording is {pct(fam["unseen"]["recall"])}. The rule layer misses scams that avoid its phrases. The Gemini
semantic layer is designed to close this gap, but it needs a live model, so **it is not measured here**.

**Missing transcript.** With a transcript, recall is {pct(tr["True"]["recall"])}. Without one it is
{pct(tr["False"]["recall"])}, because only payment signals remain.

| Language | Scam cases | Recall |
| --- | --- | --- |
{lang}

| Scam type | Scam cases | Recall |
| --- | --- | --- |
{kind}

## 3. Honest situations that still get friction

| Situation | Cases | Heads-up or more | Slow down or hold |
| --- | --- | --- | --- |
{benign}

Used-car purchases and genuine family emergencies are the clear weak spots: a large first payment under time
pressure looks like a scam payment. The product answer is that a hold is never a final denial; it ends with
a bank call-back, not a refusal.

## 4. Timing

* Decision time per assessment: median {c["latency_ms"]["p50"]} ms, 95th percentile {c["latency_ms"]["p95"]} ms (rule engine on one CPU core, excluding network).
* Of {t["scams_with_transcript"]:,} scams that had a transcript, Vigil raised a flag before the payment in
  {pct(t["share_warned_before_payment"])} of them, with a median lead of {t["median_lead_seconds"]} seconds
  (10th percentile {t["p10_lead_seconds"]} s). In the other cases the conversation alone did not look risky
  enough until the payment itself was seen, which is why the payment moment matters.
* Calibration error (ECE) is {c["calibration_ece"]}. Weights are hand-set priors, not fitted to real fraud, so
  the score is a ranking aid and must be re-calibrated on real labels before being read as a probability.

## 5. Mule-account detection

{net["true_mules"]} mule accounts and {net["hard_negative_accounts"]} look-alikes (shops, payroll, charity collectors).

| Rule | Flagged | Precision | Recall | Look-alikes flagged |
| --- | --- | --- | --- | --- |
{nrules}

Vigil's graph score recovered most members of {net["rings_with_majority_recovered"]} of the
{net["rings_total"]} injected rings. **This is nearly perfect because we generated the
graph and the detector together.** Real transfer networks are noisier. Treat it as a demonstration that
passing-through behaviour, shared devices and guilt-by-association separate mules from look-alikes better than a
fan-in rule, not as a measured accuracy.

## 6. Sharing across banks

Payment-only scams, evaluated on the second half of a stream, with {pct(0.7, 0)} of confirmed losses reported
by one of three banks. A payee counts as flagged only when at least two banks report it.

| | Scams caught | False alarms |
| --- | --- | --- |
| Without sharing | {pct(ex["without_exchange"]["recall"])} | {pct(ex["without_exchange"]["fpr"], 2)} |
| With sharing | {pct(ex["with_exchange"]["recall"])} | {pct(ex["with_exchange"]["fpr"], 2)} |

**This lift is overstated.** The synthetic scammers reuse a small pool of payees, so a report is very likely to
match a later scam. Real scammers rotate accounts faster. The honest claim is directional: sharing helps in
proportion to how often payees repeat, and the mechanism (corroboration, expiry, retraction, rate limits) is
tested separately in `tests/test_network.py`.

## 7. What is not evaluated

* Gemini's semantic layer and composed messages (needs a live model and a labelled multilingual set).
* Real call audio and speech recognition errors. Typos injected into text were not handled and are a known miss.
* Hindi and Telugu warning text by native speakers.
* Any real customer data, real fraud labels, or fairness across user groups.
* Adversarial adaptation: scammers who learn the phrases Vigil listens for.

## Reproduce

```bash
make eval            # writes artifacts/eval/results.json and the UI copy
python scripts/gen_eval_doc.py
pytest tests/test_eval_gates.py   # regression gates on relative claims
```
"""
(ROOT / "docs/EVALUATION.md").write_text(doc, encoding="utf-8")
print("wrote docs/EVALUATION.md")
